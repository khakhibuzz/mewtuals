function createLookup<const Values extends readonly string[]>(
  values: Values,
): Readonly<Record<Values[number], true>> {
  return Object.freeze(
    Object.fromEntries(values.map((value) => [value, true])),
  ) as Readonly<Record<Values[number], true>>;
}

