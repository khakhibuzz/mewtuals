import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { userInfo } from "node:os";
import { join } from "node:path";
import { parseEnv } from "node:util";

const generatedHeader = "# Generated by Mewtuals local setup. Development only.";

/** @param {Record<string, string | undefined>} environment */
export function localDatabasePort(environment = process.env) {
  const port = environment.MEWTUALS_LOCAL_DATABASE_PORT ?? "55432";
  if (!/^[1-9]\d{3,4}$/.test(port) || Number(port) < 1024 || Number(port) > 65535) {
    throw new Error("MEWTUALS_LOCAL_DATABASE_PORT must be a port from 1024 to 65535.");
  }
  return port;
}

export function localDatabaseUrl(databaseName, options = {}) {
  if (!["mewtuals", "mewtuals_test"].includes(databaseName)) {
    throw new Error("Local commands may use only the Mewtuals app or test database.");
  }
  const port = localDatabasePort({
    MEWTUALS_LOCAL_DATABASE_PORT: options.port ?? localDatabasePort(),
  });
  const username = options.username ?? userInfo().username;
  return `postgresql://${encodeURIComponent(username)}@127.0.0.1:${port}/${databaseName}`;
}

export function configureLocalEnvironment(projectRoot, options = {}) {
  const port = options.port ?? localDatabasePort();
  const databaseUrl = localDatabaseUrl("mewtuals", { ...options, port });
  const paths = [join(projectRoot, ".env.local"), join(projectRoot, ".dev.vars")];
  if (paths.some(existsSync)) {
    const contents = paths.map((path) => existsSync(path) ? readFileSync(path, "utf8") : "");
    const existing = parseEnv(contents[0]);
    if (
      !contents[0].startsWith(generatedHeader) || contents[0] !== contents[1] ||
      existing.DATABASE_URL !== databaseUrl || existing.NODE_ENV !== "development" ||
      existing.MEWTUALS_LOCAL_DATABASE_PORT !== port ||
      !/^[A-Za-z0-9_-]{64}$/.test(existing.SESSION_SECRET ?? "")
    ) {
      throw new Error(
        "Refusing to replace existing local configuration. Review .env.local and .dev.vars; " +
        "setup only reuses matching generated files for this local database.",
      );
    }
    return false;
  }

  const contents = [
    generatedHeader,
    `MEWTUALS_LOCAL_DATABASE_PORT=${port}`,
    `DATABASE_URL=${databaseUrl}`,
    "NODE_ENV=development",
    `SESSION_SECRET=${randomBytes(48).toString("base64url")}`,
    "MEWTUALS_DEV_AUTH=true",
    "ADMIN_EMAILS=mewtuals-mobile-e2e@example.test",
    "RESEND_API_KEY=",
    "EMAIL_FROM=",
    "GOOGLE_CLIENT_ID=",
    "GOOGLE_CLIENT_SECRET=",
    "",
  ].join("\n");

  writeFileSync(paths[0], contents, { flag: "wx", mode: 0o600 });
  try {
    writeFileSync(paths[1], contents, { flag: "wx", mode: 0o600 });
  } catch (error) {
    unlinkSync(paths[0]);
    throw error;
  }
  return true;
}
